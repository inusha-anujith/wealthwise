CREATE TABLE payroll_rule_sets (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_from     DATE         NOT NULL UNIQUE,
    employee_epf_rate  NUMERIC(5, 2) NOT NULL,
    employer_epf_rate  NUMERIC(5, 2) NOT NULL,
    etf_rate           NUMERIC(5, 2) NOT NULL,
    source_note        VARCHAR(500) NOT NULL
);

CREATE TABLE tax_brackets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_set_id  BIGINT         NOT NULL REFERENCES payroll_rule_sets (id),
    lower_bound  NUMERIC(15, 2) NOT NULL,
    upper_bound  NUMERIC(15, 2),
    rate         NUMERIC(5, 2)  NOT NULL,
    deduction    NUMERIC(15, 2) NOT NULL
);

CREATE INDEX idx_tax_brackets_rule_set ON tax_brackets (rule_set_id);

CREATE TABLE salary_profiles (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT         NOT NULL UNIQUE REFERENCES users (id),
    gross_salary           NUMERIC(15, 2) NOT NULL CHECK (gross_salary > 0),
    epf_earnings           NUMERIC(15, 2) NOT NULL CHECK (epf_earnings >= 0),
    needs_percent          INTEGER        NOT NULL CHECK (needs_percent BETWEEN 0 AND 100),
    wants_percent          INTEGER        NOT NULL CHECK (wants_percent BETWEEN 0 AND 100),
    savings_percent        INTEGER        NOT NULL CHECK (savings_percent BETWEEN 0 AND 100),
    emergency_fund_months  INTEGER        NOT NULL CHECK (emergency_fund_months BETWEEN 0 AND 24),
    high_interest_debt     NUMERIC(15, 2) NOT NULL CHECK (high_interest_debt >= 0),
    CHECK (needs_percent + wants_percent + savings_percent = 100),
    CHECK (epf_earnings <= gross_salary)
);

