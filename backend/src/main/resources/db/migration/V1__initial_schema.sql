CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    base_currency VARCHAR(255) NOT NULL
);

CREATE TABLE transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL REFERENCES users (id),
    type             VARCHAR(255)   NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    amount           NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    category         VARCHAR(255)   NOT NULL,
    transaction_date DATE           NOT NULL,
    description      VARCHAR(500)
);

CREATE TABLE assets (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT         NOT NULL REFERENCES users (id),
    ticker_symbol          VARCHAR(255)   NOT NULL,
    shares_owned           INTEGER        NOT NULL CHECK (shares_owned > 0),
    average_purchase_price NUMERIC(15, 2) NOT NULL CHECK (average_purchase_price > 0)
);

CREATE TABLE dividends (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id     BIGINT         NOT NULL REFERENCES assets (id),
    amount       NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    payment_date DATE           NOT NULL
);

CREATE TABLE fixed_deposits (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL REFERENCES users (id),
    bank_name        VARCHAR(255)   NOT NULL,
    principal_amount NUMERIC(15, 2) NOT NULL CHECK (principal_amount > 0),
    interest_rate    NUMERIC(5, 2)  NOT NULL CHECK (interest_rate > 0 AND interest_rate <= 100),
    start_date       DATE           NOT NULL,
    duration_months  INTEGER        NOT NULL CHECK (duration_months > 0)
);

CREATE INDEX idx_transactions_user_date ON transactions (user_id, transaction_date DESC);
CREATE INDEX idx_assets_user ON assets (user_id);
CREATE INDEX idx_dividends_asset ON dividends (asset_id);
CREATE INDEX idx_fixed_deposits_user ON fixed_deposits (user_id);