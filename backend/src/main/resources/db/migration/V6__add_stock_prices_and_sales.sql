ALTER TABLE assets
    ADD COLUMN current_price    NUMERIC(15, 2) CHECK (current_price > 0),
    ADD COLUMN price_updated_on DATE;

-- A fully sold stock keeps its history with zero shares.
ALTER TABLE assets
    DROP CONSTRAINT assets_shares_owned_check;

ALTER TABLE assets
    ADD CONSTRAINT chk_assets_shares_owned CHECK (shares_owned >= 0);

CREATE TABLE asset_sales (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id      BIGINT         NOT NULL REFERENCES assets (id),
    shares_sold   INTEGER        NOT NULL CHECK (shares_sold > 0),
    sale_price    NUMERIC(15, 2) NOT NULL CHECK (sale_price > 0),
    sale_date     DATE           NOT NULL,
    proceeds      NUMERIC(15, 2) NOT NULL,
    cost_basis    NUMERIC(15, 2) NOT NULL,
    realized_gain NUMERIC(15, 2) NOT NULL
);

CREATE INDEX idx_asset_sales_asset ON asset_sales (asset_id);

ALTER TABLE transactions
    DROP CONSTRAINT chk_transactions_source_type,
    DROP CONSTRAINT chk_transactions_category;

ALTER TABLE transactions
    ADD CONSTRAINT chk_transactions_source_type
        CHECK (source_type IN ('MANUAL', 'ASSET_PURCHASE', 'ASSET_SALE', 'DIVIDEND', 'FIXED_DEPOSIT')),
    ADD CONSTRAINT chk_transactions_category
        CHECK (
            (type = 'INCOME' AND category IN (
                'SALARY', 'SIDE_INCOME', 'RENTAL_INCOME', 'FD_INTEREST',
                'OTHER_INCOME', 'DIVIDEND_INCOME', 'FIXED_DEPOSIT_RETURN', 'STOCK_SALE'
            ))
            OR
            (type = 'EXPENSE' AND category IN (
                'HOUSEHOLD', 'HOUSING', 'LOANS', 'INSURANCE', 'UTILITIES', 'TRANSPORT',
                'HEALTH', 'EDUCATION_FEES', 'DINING_ENTERTAINMENT', 'SHOPPING',
                'OTHER_EXPENSE', 'STOCK_PURCHASE', 'FIXED_DEPOSIT'
            ))
        );